using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;

namespace SkillIssue.Templates.Generator;

[Generator]
public sealed class TemplateGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var templates = context.AdditionalTextsProvider.Where(static file =>
            Path.GetExtension(file.Path).Equals(".html", StringComparison.OrdinalIgnoreCase)
        );
        context.RegisterSourceOutput(templates, Generate);
    }

    private static void Generate(SourceProductionContext context, AdditionalText file)
    {
        var source = file.GetText(context.CancellationToken);
        if (source is null)
        {
            return;
        }

        string className = Path.GetFileNameWithoutExtension(file.Path) + "Data";
        string hintName = $"{className}.g.cs";
        string template = source.ToString();
        var parameters = new List<string>();
        var members = new HashSet<string>(StringComparer.Ordinal);
        var lookups = new List<string>();
        int offset = 0;

        foreach (var tag in TemplateSyntax.ReadTags(template, context.CancellationToken))
        {
            if (tag.Kind != TemplateTagKind.Parameter)
            {
                continue;
            }

            string property =
                tag.Name.Length == 0
                    ? string.Empty
                    : char.ToUpperInvariant(tag.Name[0]) + tag.Name[1..];
            if (
                tag.Argument is not string type
                || !template.AsSpan(offset, tag.Index - offset).Trim().IsEmpty
                || !members.Add(property)
                || SyntaxFactory.ParseTypeName(type).ContainsDiagnostics
            )
            {
                int line = source.Lines.GetLineFromPosition(tag.Index).LineNumber + 1;
                string error = $"#error Invalid template parameter in {file.Path}:{line}";
                context.AddSource(hintName, SourceText.From(error, Encoding.UTF8));
                return;
            }

            parameters.Add($"{type} {property}");
            lookups.Add($"\"{tag.Name}\" => (true, {property}),");
            offset = tag.Index + tag.Length;
        }

        if (parameters.Count == 0)
        {
            return;
        }

        string generated = $$"""
            // <auto-generated/>
            #nullable enable
            namespace SkillIssue.Templates;

            internal sealed record {{className}}(
                {{string.Join(",\n    ", parameters)}}
            ) : ITemplateData
            {
                public (bool Found, object? Value) ReadValue(string name) => name switch
                {
                    {{string.Join("\n        ", lookups)}}
                    _ => (false, null),
                };
            }
            """;
        context.AddSource(hintName, SourceText.From(generated, Encoding.UTF8));
    }
}
